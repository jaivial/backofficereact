import { chromium } from "@playwright/test";
const b = await chromium.connectOverCDP("http://127.0.0.1:9362");
const p = b.contexts()[0].pages().find(x=>x.url().includes("3098"));
await p.keyboard.press("Escape"); await p.waitForTimeout(400);
await p.getByTestId("pos-rail-factura").click(); await p.waitForTimeout(1500);
const dlg = p.locator('[role=dialog]').last();
console.log("FACTURA:", (await dlg.innerText().catch(()=>"(none)")).replace(/\n+/g," | ").slice(0,700));
await p.screenshot({ path: "/tmp/pos52.png" });
await p.keyboard.press("Escape"); await p.waitForTimeout(400);
await p.getByTestId("pos-rail-facturacion").click(); await p.waitForTimeout(1500);
console.log("FACTURACION:", (await p.locator('[role=dialog]').last().innerText().catch(()=>"(none)")).replace(/\n+/g," | ").slice(0,500));
await p.screenshot({ path: "/tmp/pos53.png" });
await p.keyboard.press("Escape");
await b.close();
