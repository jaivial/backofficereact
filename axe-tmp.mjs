import { chromium } from "@playwright/test";
import { readFileSync } from "node:fs";
const axe = readFileSync("node_modules/axe-core/axe.min.js", "utf8");
const b = await chromium.connectOverCDP("http://127.0.0.1:9362");
const p = b.contexts()[0].pages().find(x=>x.url().includes("3098"));
const run = async (label) => {
  await p.addScriptTag({ content: axe });
  const r = await p.evaluate(async () => await window.axe.run(document, { runOnly: ["wcag2a","wcag2aa","wcag21aa"], resultTypes: ["violations"] }));
  console.log(`\n== ${label}: ${r.violations.length} violations`);
  for (const v of r.violations) console.log(`- [${v.impact}] ${v.id}: ${v.help} (${v.nodes.length}) e.g. ${v.nodes[0]?.target[0]}`);
};
await p.goto("http://127.0.0.1:3098/app/pos", { waitUntil: "networkidle" }); await p.waitForTimeout(2000); await run("sell-empty");
await p.getByTestId("pos-open-visit-" + (await p.evaluate(()=>[...document.querySelectorAll('[data-testid^="pos-open-visit-"]')].map(e=>e.dataset.testid.split('-').pop())[0]))).click(); await p.waitForTimeout(1500); await run("sell-ticket");
await p.getByTestId("pos-rail-total").click(); await p.waitForTimeout(1200); await run("checkout"); await p.keyboard.press("Escape");
await p.getByTestId("pos-ticket-panel").click().catch(()=>{}); await p.getByTestId("pos-rail-mesa").click(); await p.waitForTimeout(1200); await run("tables"); await p.keyboard.press("Escape");
await p.goto("http://127.0.0.1:3098/app/pos?section=kitchen", { waitUntil: "networkidle" }); await p.waitForTimeout(1500); await run("kitchen");
await p.goto("http://127.0.0.1:3098/app/pos?section=settings", { waitUntil: "networkidle" }); await p.waitForTimeout(1500); await run("settings");
await p.goto("http://127.0.0.1:3098/app/pos?section=reports", { waitUntil: "networkidle" }); await p.waitForTimeout(1500); await run("reports");
await p.goto("http://127.0.0.1:3098/app/pos?section=catalog", { waitUntil: "networkidle" }); await p.waitForTimeout(1500); await run("catalog");
await b.close();
